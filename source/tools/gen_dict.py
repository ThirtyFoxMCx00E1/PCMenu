#!/usr/bin/env python3
"""Builds jni/pcdict.h from tools/pcdict.txt (ENGLISH|FR|DE|IT|ES|ID|AR per line)."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
src, dst = os.path.join(here, 'pcdict.txt'), os.path.join(here, '..', 'jni', 'pcdict.h')
def q(s): return 'NULL' if not s else '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
rows, seen = [], set()
for n, line in enumerate(open(src, encoding='utf-8'), 1):
    line = line.rstrip('\n')
    if not line.strip() or line.startswith('#'): continue
    c = line.split('|')
    if len(c) != 7: sys.exit('pcdict.txt:%d: expected 7 columns, got %d' % (n, len(c)))
    if c[0] in seen: sys.exit('pcdict.txt:%d: duplicate %s' % (n, c[0]))
    for k in range(5):
        if any(ord(ch) > 127 for ch in c[k]) or c[k] != c[k].upper(): sys.exit('pcdict.txt:%d: column %d must be ASCII upper case' % (n, k + 1))
    seen.add(c[0]); rows.append(c)
with open(dst, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/gen_dict.py from tools/pcdict.txt - edit that file, not this one.\n#ifndef PCDICT_H\n#define PCDICT_H\n')
    f.write('struct DictEntry { const char* en; const char* fr; const char* de; const char* it; const char* es; const char* id; const char* ar; };\n')
    f.write('static const DictEntry kDict[] = {\n')
    for c in rows: f.write('    { ' + ', '.join(q(x) for x in c) + ' },\n')
    f.write('};\nstatic const int kDictCount = (int)(sizeof(kDict) / sizeof(kDict[0]));\n#endif\n')
print('%d entries -> %s' % (len(rows), os.path.relpath(dst)))
